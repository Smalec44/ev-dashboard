// NFD splits "ü" into "u" + a combining mark, which the a-z filter then drops.
function fold(value: string): string {
  return value.toLowerCase().normalize("NFD").replace(/[^a-z]/g, "");
}

// Folded once at module load rather than per call: findRegion runs on every
// keystroke, and re-folding ~5000 keys each time is wasted work at this size.
const CANDIDATES: {
  region: Region;
  keys: string[];
  /** Name keys only. Kept apart so suggestions can rank a town called "Sion"
   *  above every town that merely sits in canton SG. */
  nameKeys: string[];
  cantonKey: string;
}[] = REGIONS.map((region) => ({
  region,
  keys: [region.slug, region.city, region.canton, ...region.aliases].map(fold),
  nameKeys: [region.slug, region.city, ...region.aliases].map(fold),
  cantonKey: fold(region.canton),
}));

/**
 * Best matches for a partial query, for the search suggestions. Name matches
 * outrank canton matches — typing "s" should offer St. Gallen, not every town
 * in canton SG — and an exact canton code still lists that canton's towns.
 * Within a tier REGIONS' population order decides, so "b" offers Bern first.
 *
 * The cap is the point: a native datalist holding all 1000 towns makes the
 * browser render a viewport-tall popup for a single-letter query.
 */
export function matchRegions(query: string, limit = 8): Region[] {
  const needle = fold(query);
  if (!needle) return REGIONS.slice(0, limit);

  const nameExact: Region[] = [];
  const cantonExact: Region[] = [];
  const namePrefix: Region[] = [];
  const nameSubstring: Region[] = [];
  const cantonPrefix: Region[] = [];
  for (const { region, nameKeys, cantonKey } of CANDIDATES) {
    if (nameKeys.includes(needle)) nameExact.push(region);
    else if (cantonKey === needle) cantonExact.push(region);
    else if (nameKeys.some((key) => key.startsWith(needle))) namePrefix.push(region);
    else if (nameKeys.some((key) => key.includes(needle))) nameSubstring.push(region);
    else if (cantonKey.startsWith(needle)) cantonPrefix.push(region);
    // Cheapest possible exit: the best tier alone can already fill the list.
    if (nameExact.length >= limit) break;
  }
  return [
    ...nameExact,
    ...cantonExact,
    ...namePrefix,
    ...nameSubstring,
    ...cantonPrefix,
  ].slice(0, limit);
}

export function findRegion(query: string): Region | null {
  const needle = fold(query);
  if (!needle) return null;

  const exact = CANDIDATES.find(({ keys }) => keys.includes(needle));
  if (exact) return exact.region;

  const partial = CANDIDATES.find(({ keys }) =>
    keys.some((key) => key.startsWith(needle) || needle.startsWith(key)),
  );
  return partial ? partial.region : null;
}
